export type Lang = "en" | "fil"
const KEY = "free247editor-lang"
let lang: Lang = (() => {
  try {
    return localStorage.getItem(KEY) === "fil" ? "fil" : "en"
  } catch {
    return "en"
  }
})()
const subs = new Set<() => void>()

export function setLang(next: Lang) {
  lang = next
  try {
    localStorage.setItem(KEY, next)
  } catch {
    // this session only
  }
  document.documentElement.lang = next === "fil" ? "tl" : "en"
  subs.forEach((fn) => fn())
}

export const isKey = (s: string): s is Key => s in en

export function translate(l: Lang, key: Key, vars: Record<string, string | number> = {}) {
  const text = (l === "fil" && fil[key]) || en[key]
  return text.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""))
}

export type T = (key: Key, vars?: Record<string, string | number>) => string

// Known engine error codes read from this table; anything else shows the engine's own words.
export function errorText(t: T, e: { code?: string; message?: string }, p: string) {
  const key = `err.${e.code}`
  return isKey(key) ? t(key, { p }) : e.message || String(e)
}

// Components read strings through this hook, so the FIL/EN pill re-renders them.
export function useT(): [T, Lang] {
  const l = useSyncExternalStore(
    (fn) => {
      subs.add(fn)
      return () => void subs.delete(fn)
    },
    () => lang
  )
  return [(key, vars) => translate(l, key, vars), l]
}
